// Run in the application image with repository mounted at /work and output at /output.
const assert = require("node:assert/strict");
const { mkdtempSync, mkdirSync, writeFileSync, readFileSync } = require("node:fs");
const { EventEmitter } = require("node:events");
const { chromium } = require("/app/node_modules/playwright");
const { Controller } = require("../dist/src/session/controller");
const { Scheduler } = require("../dist/src/session/schedules");
const { createApp } = require("../dist/src/server/app");
(async () => {
  const root = mkdtempSync("/tmp/ea-attempts-");
  mkdirSync(root + "/recordings/old", { recursive: true });
  writeFileSync(root + "/recordings/old/session.json", JSON.stringify({ id: "old", meetingName: "Old meeting", botName: "Bot", createdAt: "2026-10-26T06:00:00Z", status: "completed", files: [] }));
  const workers = [];
  const controller = new Controller(root, () => {
    const w = new EventEmitter();
    w.send = m => { if (m.type === "stop") setImmediate(() => { w.emit("message", { type: "done", files: [] }); w.emit("exit", 0); }); };
    w.kill = () => w.emit("exit", 0); workers.push(w); return w;
  });
  const server = createApp(controller, { publicDir: "/work/public", scheduler: new Scheduler(root, controller) });
  await new Promise(resolve => server.listen(0, "127.0.0.1", resolve));
  const browser = await chromium.launch({ headless: true, args: ["--no-sandbox"] });
  const page = await browser.newPage({ viewport: { width: 1100, height: 1000 } });
  if (process.env.ATTEMPTS_OLD_UI) await page.route("**/app.js", route => route.fulfill({ body: readFileSync("/output/app-before.js"), contentType: "text/javascript" }));
  const errors = [];
  page.on("pageerror", e => errors.push(e.message));
  try {
    const session = await controller.startSession({ meetingUrl: "https://zoom.us/j/12345678901", meetingName: "Recovery check", botName: "HRM Assistant", recordingMode: "audio" });
    const attempts = [{ number: 1, startedAt: session.createdAt, endedAt: session.createdAt, outcome: "failed", error: "zoom_requires_rtms: <img src=x onerror=alert(1)> https://zoom.us/?pwd=private" }];
    workers[0].emit("message", { type: "attempts", attempts, nextRetryAt: new Date(Date.now() + 60000).toISOString() });
    await page.goto("http://127.0.0.1:" + server.address().port);
    const card = page.locator("#sessions article").filter({ hasText: "Recovery check" });
    const details = card.locator("details.attempts");
    await details.locator("summary").waitFor({ timeout: 2500 });
    assert.match(await details.locator("summary").innerText(), /Attempts: 1\/4/);
    assert.equal(await details.evaluate(el => el.classList.contains("has-failures")), true);
    assert.match(await card.locator(".retry-countdown").innerText(), /Retry in \d+s/);
    const before = await card.locator(".retry-countdown").innerText();
    await page.waitForTimeout(1200);
    assert.notEqual(await card.locator(".retry-countdown").innerText(), before);
    await details.locator("summary").click();
    assert.match(await details.innerText(), /pwd=\[redacted\]/);
    assert.equal(await details.locator("img").count(), 0);
    assert.equal(await page.locator("#sessions article").filter({ hasText: "Old meeting" }).locator("details.attempts").count(), 0);
    await details.locator("summary").focus();
    const two = [...attempts, { number: 2, startedAt: session.createdAt, endedAt: session.createdAt, outcome: "connected" }];
    workers[0].emit("message", { type: "attempts", attempts: two });
    workers[0].emit("message", { type: "status", status: "recording" });
    await page.evaluate(() => refresh());
    assert.equal(await details.evaluate(el => el.open), true);
    assert.equal(await details.locator("summary").evaluate(el => el === document.activeElement), true);
    assert.match(await details.locator("summary").innerText(), /Attempts: 2\/4/);
    assert.match(await card.innerText(), /Connected on attempt 2/);
    assert.equal(await details.evaluate(el => el.classList.contains("has-failures")), true);
    assert.equal(await card.locator(".retry-countdown").count(), 0);
    const ink = await details.locator("summary").evaluate(el => getComputedStyle(el).color);
    assert.match(ink, /^rgb\(/);
    await page.screenshot({ path: "/output/attempts-desktop.png", fullPage: true });
    workers[0].emit("message", { type: "done", files: [] }); workers[0].emit("exit", 0);
    await page.evaluate(() => refresh());
    assert.equal(await details.evaluate(el => el.open), true);
    const second = await controller.startSession({ meetingUrl: "https://zoom.us/j/12345678901", meetingName: "Stop pending retry", botName: "Bot" });
    workers[1].emit("message", { type: "attempts", attempts: [{ ...attempts[0], startedAt: second.createdAt }], nextRetryAt: new Date(Date.now() + 10000).toISOString() });
    await page.evaluate(() => refresh());
    await page.locator("#stop").click();
    await page.waitForFunction(() => document.getElementById("stop").disabled);
    assert.equal(controller.getSession(second.id).status, "completed");
    assert.equal(controller.getSession(second.id).nextRetryAt, undefined);
    await page.setViewportSize({ width: 390, height: 844 });
    await page.evaluate(() => refresh());
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
    await page.screenshot({ path: "/output/attempts-mobile.png", fullPage: true });
    assert.deepEqual(errors, []);
    console.log("PASS attempts: retry countdown, failure history, recovery, focus/open persistence, redaction, stop, old sessions, mobile");
  } finally { await browser.close(); await new Promise(resolve => server.close(resolve)); }
})().catch(error => { console.error(error); process.exitCode = 1; });
